"""Build C ABI products with native Nim and retain its module/backend graphs."""
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, sort_keys=True, indent=2) + "\n")


def companion_header(raw, guard):
    original = re.search(r"^#ifndef (\w+)$", raw, re.M)
    if original is None:
        raise ValueError("native Nim header has no include guard")
    original = original.group(1)
    lines = []
    declarations = []
    for line in raw.splitlines():
        if line in ["#ifndef " + original, "#define " + original]:
            line = line.replace(original, guard)
        declaration = re.fullmatch(
            r'(?:extern "C"\s+)?((?:N_LIB_PRIVATE|N_LIB_IMPORT|N_LIB_EXPORT)\s+[^;]+;)', line)
        if declaration:
            # Keep all native declaration types/macros intact. Nim's C++ header
            # emits `extern "C" extern ...`, rejected by GNU C++; the companion
            # expresses the same C linkage as a block instead.
            declaration = declaration.group(1)
            declarations.append(declaration)
            lines.extend(["#ifdef __cplusplus", 'extern "C" {', "#endif", declaration,
                          "#ifdef __cplusplus", "}", "#endif"])
        else:
            if 'extern "C"' in line:
                raise ValueError("unsupported native header linkage shape")
            lines.append(line)
    return "\n".join(lines) + "\n", declarations


def includes(arguments):
    result = []
    iterator = iter(arguments)
    for argument in iterator:
        if argument in ["-I", "-isystem", "-iquote", "-idirafter"]:
            result.append(next(iterator))
        elif argument.startswith("-I") and len(argument) > 2:
            result.append(argument[2:])
        elif argument.startswith("-isystem") and len(argument) > len("-isystem"):
            result.append(argument[len("-isystem"):])
    return result


def code_without_native_command_comments(text):
    # Comparison only: retain both original byte streams. A normal Nim build
    # adds these two diagnostic comments, omitted by its genScript phase.
    return re.sub(r'^(/\* Generated by Nim Compiler v[^\n]+ \*/\n)'
                  r'/\* Compiled for: [^\n]+ \*/\n/\* Command for C compiler:\n.*?\*/\n',
                  r'\1', text, count=1, flags=re.S | re.M)


def build(out, environment, spec_file, nim, nm, cc):
    out, environment = Path(out), Path(environment).resolve()
    project = out / "project"
    specs = json.loads(Path(spec_file).read_text())
    metadata = json.loads((environment / "metadata.json").read_text())
    package = json.loads(subprocess.check_output(["nimble", "--silent", "dump", "--json"],
                        cwd=project, text=True))
    source_root = (project / package.get("srcDir", "")).resolve()
    if not source_root.is_relative_to(project):
        raise ValueError("native Nimble source directory escapes project")
    sdk_check = Path(os.environ["TMPDIR"]) / "sdk-check"
    sdk_check.mkdir()
    (sdk_check / "sdk.nim").write_text("discard\n")
    sdk = json.loads(subprocess.check_output([nim, "dump", "--dump.format:json", "--verbosity:0",
                                            str(sdk_check / "sdk.nim")], cwd=sdk_check, text=True))
    sdk_root = Path(sdk["libpath"]).resolve()
    if sdk["version"] != metadata["profile"]["toolVersions"]["nim"]:
        raise ValueError("Nim SDK changed from the captured profile")
    dependencies = []
    for dependency in metadata["profile"]["dependencies"]:
        path = Path(subprocess.check_output(["nimble", "--silent", "path", dependency["name"]],
                    cwd=project, text=True).strip()).resolve()
        if not path.is_relative_to(environment / "pkgs2"):
            raise ValueError("native package path is not captured: " + dependency["name"])
        dependencies.append((path, dependency))
    (out / "include/nimble").mkdir(parents=True)
    (out / "lib/pkgconfig").mkdir(parents=True)
    (out / "native-proof").mkdir()
    shutil.copyfile(sdk_root / "nimbase.h", out / "include/nimbase.h")
    write_json(out / "native-proof/package.json", package)
    write_json(out / "native-proof/sdk.json", sdk)
    def source_owner(path):
        if path.is_relative_to(project):
            return {"kind": "project", "path": str(path.relative_to(project))}
        if path.is_relative_to(sdk_root):
            return {"kind": "sdk", "path": str(path.relative_to(sdk_root))}
        for root, dependency in dependencies:
            if path.is_relative_to(root):
                return {"kind": "dependency", "package": dependency["name"],
                        "version": dependency["native"]["version"],
                        "revision": dependency["native"]["vcsRevision"],
                        "path": str(path.relative_to(root))}
        raise ValueError("compiler input has no captured source owner: " + str(path))
    models = {}
    for name, spec in specs.items():
        entry = (project / spec["module"]).resolve()
        if not entry.is_file() or not entry.is_relative_to(source_root):
            raise ValueError("native product module is not a project production source")
        proof = out / "native-proof" / name
        proof.mkdir()
        cache = Path(os.environ["TMPDIR"]) / "native-cache" / name
        cache.mkdir(parents=True)
        library = out / "lib" / ("lib" + name + ".so")
        command = [nim, spec["backend"], "--app:lib", "--noMain:on", "--threads:on",
                   "--mm:" + spec["memoryManager"], "-d:release", "--lineDir:on", "--genScript:on",
                   "--nimMainPrefix:" + spec["prefix"], "--header:" + name + ".h",
                   "--nimcache:" + str(cache), "--out:" + str(library), str(entry)]
        subprocess.run(command, cwd=project, check=True)
        native_file = cache / ("lib" + name + ".json")
        native = json.loads(native_file.read_text())
        shutil.copyfile(native_file, proof / "generation.json")
        shutil.copyfile(cache / (entry.stem + ".deps"), proof / "sources.deps")
        if Path(native["outputFile"]) != library or not native["compile"] or not native["link"]:
            raise ValueError("native compiler did not emit the requested library build")
        compile_sources = []
        include_paths = []
        for filename, command_text in native["compile"]:
            path = Path(filename).resolve()
            if path.is_relative_to(cache):
                stored = proof / "generation" / path.relative_to(cache)
                stored.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, stored)
                owner = {"kind": "generated", "path": str(stored.relative_to(out)),
                         "generationPath": str(stored.relative_to(out)), "generationSha256": sha(stored)}
            else:
                owner = source_owner(path)
            compile_sources.append(owner | {"sha256": sha(path), "compilerInput": str(path)})
            include_paths.extend(includes(shlex.split(command_text)))
        expected_suffix = ".c" if spec["backend"] == "c" else ".cpp"
        if not any(s["kind"] == "generated" and s["path"].endswith(expected_suffix) for s in compile_sources):
            raise ValueError("compiler graph has no generated unit for the requested backend")
        include_paths.extend(includes(shlex.split(os.environ.get("NIX_CFLAGS_COMPILE", ""))))
        native_sources = {}
        deps_file = cache / (entry.stem + ".deps")
        for filename in deps_file.read_text().splitlines():
            path = Path(filename).resolve()
            if not path.is_file():
                raise ValueError("compiler dependency is missing: " + filename)
            owner = source_owner(path)
            native_sources[filename] = owner | {"sha256": sha(path)}
        if not any(v["kind"] == "project" and v["path"] == str(entry.relative_to(project)) for v in native_sources.values()):
            raise ValueError("native graph omitted the declared project module")
        # genScript simplifies source/object paths for an exported script and
        # does not execute the backend. Let native Nim drive compilation so
        # project/dependency C files retain their proper paths and options.
        compile_command = [argument for argument in command if argument != "--genScript:on"]
        compile_command.insert(-1, "--forceBuild:on")
        compile_command.insert(-1, "--listCmd")
        subprocess.run(compile_command, cwd=project, check=True)
        actual = json.loads(native_file.read_text())
        if [row[0] for row in actual["compile"]] != [row[0] for row in native["compile"]]:
            raise ValueError("native compilation graph changed after generation")
        for record in compile_sources:
            actual_source = Path(record["compilerInput"])
            if record["kind"] == "generated":
                generation_source = out / record["generationPath"]
                if code_without_native_command_comments(actual_source.read_text()) != code_without_native_command_comments(generation_source.read_text()):
                    raise ValueError("native backend code changed between generation and compilation: " + str(actual_source))
                stored = proof / "compiled" / actual_source.relative_to(cache)
                stored.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(actual_source, stored)
                record.update(path=str(stored.relative_to(out)), sha256=sha(stored),
                    phaseComparison="only native target/compiler command comments may differ; both originals retained")
            elif sha(actual_source) != record["sha256"]:
                raise ValueError("native foreign source changed during compilation")
        for filename, record in native_sources.items():
            if sha(Path(filename).resolve()) != record["sha256"]:
                raise ValueError("native dependency changed during compilation")
        actual_header = cache / (name + ".h")
        shutil.copyfile(actual_header, proof / (name + ".h"))
        if not library.is_file() or library.read_bytes()[:4] != b"\x7fELF":
            raise ValueError("native backend did not produce an ELF library")
        symbols = subprocess.check_output([nm, "-D", "--defined-only", str(library)], text=True)
        exported = {line.split()[-1] for line in symbols.splitlines() if line.split()}
        init = spec["prefix"] + "NimMain"
        wanted = [*spec["exports"], init]
        if not set(wanted) <= exported:
            raise ValueError("requested C ABI exports are absent from native ELF: " + repr(set(wanted) - exported))
        header = proof / (name + ".h")
        raw = header.read_text()
        for symbol in wanted:
            if not re.search(r"N_CDECL\([^,\n]*,\s*" + re.escape(symbol) + r"\)\(", raw):
                raise ValueError("requested export has no native cdecl header declaration: " + symbol)
        companion, declarations = companion_header(raw, "NIMBLE_" + spec["prefix"].upper() + "HEADER")
        public_header = out / "include/nimble" / (name + ".h")
        public_header.write_text(companion)
        include_paths = list(dict.fromkeys([str(out / "include"), *include_paths]))
        flags = ["-I" + path for path in include_paths]
        for compiler, language in [(cc, "c"), (str(Path(cc).with_name("c++")), "c++")]:
            subprocess.run([compiler, "-x", language, "-fsyntax-only", *flags, str(public_header)], check=True)
        version = str(package["version"])
        if "\n" in version or "\r" in version:
            raise ValueError("invalid native package version")
        (out / "lib/pkgconfig" / (name + ".pc")).write_text(
            "prefix=" + str(out) + "\nlibdir=${prefix}/lib\nincludedir=${prefix}/include\n\nName: " + name +
            "\nDescription: Nimble native C ABI product\nVersion: " + version +
            "\nLibs: -L${libdir} -l" + name + "\nCflags: " + " ".join(shlex.quote(flag) for flag in flags) + "\n")
        models[name] = spec | {"compiler": sdk["version"], "package": package["name"], "version": version,
            "moduleSource": str(entry.relative_to(project)),
            "library": str(library.relative_to(out)), "librarySha256": sha(library), "init": init,
            "nativeHeader": str(header.relative_to(out)), "nativeHeaderSha256": sha(header),
            "header": str(public_header.relative_to(out)), "headerSha256": sha(public_header),
            "nimbaseSha256": sha(out / "include/nimbase.h"), "declarations": declarations,
            "compilerInvocations": [command, compile_command],
            "backendGraph": {key: actual[key] for key in ["compile", "link", "linkcmd", "extraCmds", "configFiles"]},
            "graphScope": "generation.json is the native precompile graph; backendGraph selects stable fields from the native executed build cache, excluding its operational modification timestamp",
            "headerAdaptations": ["include-guard namespace", "function C linkage blocks; types unchanged"],
            "sources": native_sources, "compileSources": compile_sources, "exportedSymbols": sorted(exported),
            "includePaths": include_paths, "runtime": {"kind": "nim", "init": init,
                "lifecycle": "process-once", "threading": "single-foreign-thread", "termination": "process-lifetime"}}
    write_json(out / "native-products.json", models)


if __name__ == "__main__":
    build(*sys.argv[1:])
